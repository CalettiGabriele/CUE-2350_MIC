#!/usr/bin/env python3
"""Generates everything that depends on codebook.json (One-Pager 002 §6):

  build/symbols/s0..s3.wav   the four two-tone symbols (to /fat/.fxmic/ on the mic)
  build/fxmic_cfg.py         gesture thresholds and code table for the firmware
  app/Sources/FXMicCore/JackCodebook.swift   the decoder table for the Mac

Messages are three symbols with no two equal neighbours (equal neighbours merge into one
long symbol on the mic). Triples are picked greedily to be as far apart as possible.
"""
import itertools, json, pathlib, struct, sys, wave

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
cb = json.loads((HERE / "codebook.json").read_text())
S = len(cb["symbols"])

triples = [t for t in itertools.product(range(S), repeat=3) if t[0] != t[1] and t[1] != t[2]]
def dist(a, b): return sum(x != y for x, y in zip(a, b))
chosen = [triples[0]]
while len(chosen) < len(cb["messages"]):
    best = max((t for t in triples if t not in chosen), key=lambda t: (min(dist(t, c) for c in chosen), -triples.index(t)))
    chosen.append(best)
table = dict(zip(cb["messages"], chosen))

# --- WAVs
out = HERE / "build"; (out / "symbols").mkdir(parents=True, exist_ok=True)
import math
fs = cb["sampleRate"]
n = int(fs * cb["symbolMs"] / 1000)
fade = int(fs * 0.003)
for i, (a, b) in enumerate(cb["symbols"]):
    samples = []
    for k in range(n):
        env = min(1.0, k / fade, (n - 1 - k) / fade)
        v = 0.45 * env * (math.sin(2 * math.pi * a * k / fs) + math.sin(2 * math.pi * b * k / fs))
        samples.append(int(max(-1, min(1, v)) * 32767))
    with wave.open(str(out / "symbols" / f"s{i}.wav"), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(fs)
        w.writeframes(struct.pack("<%dh" % n, *samples))

# --- firmware config
gesture = dict(TAP=450, DBL=300, LONG=600, VLONG=3000, SHK=0.5, SHKN=2, SHKCD=1000, CLICK=280, HDBL=400,
               HOLDT=0.5, HOLD=2000, HOLDTOL=400, POLL=100, REP=250, QUIET=1000,
               LEDCH=4, LEDSL=6)  # LED pages: channels (red) and slots (white) the mic counts through
src = ["# Generated by firmware/fxmic/build.py from codebook.json: do not edit.", f"VERSION = '{cb['name']}'"]
src += [f"{k} = {v!r}" for k, v in gesture.items()]
src += [f"SYM = {cb['symbolMs']}", f"GAP = {cb['gapMs']}", f"HB = {cb['heartbeatSec'] * 1000}"]
src += ["CODES = b'" + "".join(chr(s) for t in chosen for s in t).encode("unicode_escape").decode() + "'"]
src += ["NAMES = " + repr(tuple(cb["messages"]))]
(out / "fxmic_cfg.py").write_text("\n".join(src) + "\n")

# --- Swift table
rows = ",\n".join(f'        "{m}": [{", ".join(map(str, t))}]' for m, t in table.items())
tones = ", ".join(f"({a:.0f}, {b:.0f})" for a, b in cb["symbols"])
swift = f'''// Generated by firmware/fxmic/build.py from codebook.json: do not edit.
import Foundation

public enum JackCodebook {{
    public static let name = "{cb['name']}"
    /// Two tones (Hz) of each symbol.
    public static let symbols: [(Double, Double)] = [{tones}]
    public static let symbolMs = {cb['symbolMs']}.0
    public static let heartbeatSec = {cb['heartbeatSec']}.0
    /// Message name → its three symbols.
    public static let messages: [String: [Int]] = [
{rows}
    ]
}}
'''
(ROOT / "app/Sources/FXMicCore/JackCodebook.swift").write_text(swift)
print("OK", len(table), "messages; min distance", min(dist(a, b) for a, b in itertools.combinations(chosen, 2)))
