#!/usr/bin/env python3
"""Generates Sources/FXMicCore/L10nTable.swift from translations.py and checks that every
L.t / L.f key used in the app has a row (and no row is unused).

usage: python3 scripts/l10n/generate.py
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from translations import LANGS, ROWS  # noqa: E402

# Keys that are not written as L.t("…") literals (labels from FXMicCore, picker tables, reasons).
DYNAMIC = {
    "Dictation", "Enhanced", "Command", "Computer Use", "Microphone", "Microphone in a circle",
    "Sound wave", "Dot", "Sparkles", "too short", "cancelled", "no speech", "Automatic",
    "Large v3 Turbo (632 MB, recommended)", "Large v3 (626 MB)", "Small (fast, less accurate)",
    "Base (very fast)",
}


def swift_literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def unescape_swift(literal):
    return literal.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")


def used_keys():
    keys = set(DYNAMIC)
    for path in glob.glob(os.path.join(APP, "Sources", "FXMicBridge", "*.swift")):
        source = open(path, encoding="utf-8").read()
        for match in re.finditer(r'L\.[tf]\("((?:[^"\\]|\\.)*)"', source):
            keys.add(unescape_swift(match.group(1)))
    return keys


def specifiers(text):
    return re.findall(r"%(?:\.\d+)?[@dfs]", text)


def main():
    problems = []
    seen = set()
    for row in ROWS:
        key = row[0]
        if len(row) != 1 + len(LANGS):
            problems.append(f"wrong column count: {key!r}")
            continue
        if key in seen:
            problems.append(f"duplicate key: {key!r}")
        seen.add(key)
        for lang, value in zip(LANGS, row[1:]):
            if specifiers(value) != specifiers(key):
                problems.append(f"format mismatch [{lang}] {key!r} -> {value!r}")
    used = used_keys()
    for key in sorted(used - seen):
        problems.append(f"missing translation: {key!r}")
    for key in sorted(seen - used):
        problems.append(f"unused row: {key!r}")
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    lines = [
        "// Generated by scripts/l10n/generate.py from scripts/l10n/translations.py. Do not edit.",
        "",
        "enum L10nTable {",
        f"    static let languages = [{', '.join(swift_literal(l) for l in LANGS)}]",
        "",
        "    /// [English key, " + ", ".join(LANGS) + "]",
        "    private static let rows: [[String]] = [",
    ]
    for row in sorted(ROWS, key=lambda r: r[0]):
        lines.append("        [" + ", ".join(swift_literal(cell) for cell in row) + "],")
    lines += [
        "    ]",
        "",
        "    static let table: [String: [String: String]] = {",
        "        var table: [String: [String: String]] = [:]",
        "        for row in rows {",
        "            var values: [String: String] = [:]",
        "            for (index, language) in languages.enumerated() { values[language] = row[index + 1] }",
        "            table[row[0]] = values",
        "        }",
        "        return table",
        "    }()",
        "}",
        "",
    ]
    out = os.path.join(APP, "Sources", "FXMicCore", "L10nTable.swift")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {out}: {len(ROWS)} keys x {len(LANGS)} languages")


if __name__ == "__main__":
    main()
